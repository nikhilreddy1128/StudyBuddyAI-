-- Run this in Supabase SQL Editor before enabling account sync and Global Lobby.
-- Keep Row Level Security enabled. Never put the service_role key in Streamlit or client code.

create table if not exists public.learner_progress (
  user_id uuid primary key references auth.users(id) on delete cascade,
  data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);
alter table public.learner_progress enable row level security;

drop policy if exists "Learners read own progress" on public.learner_progress;
create policy "Learners read own progress" on public.learner_progress
  for select to authenticated using (auth.uid() = user_id);
drop policy if exists "Learners insert own progress" on public.learner_progress;
create policy "Learners insert own progress" on public.learner_progress
  for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "Learners update own progress" on public.learner_progress;
create policy "Learners update own progress" on public.learner_progress
  for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

create table if not exists public.global_messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  nickname text not null check (char_length(nickname) between 1 and 32),
  content text not null check (char_length(content) between 1 and 500),
  created_at timestamptz not null default now()
);
alter table public.global_messages enable row level security;

drop policy if exists "Signed-in learners can read lobby messages" on public.global_messages;
create policy "Signed-in learners can read lobby messages" on public.global_messages
  for select to authenticated using (true);
drop policy if exists "Learners can post as themselves" on public.global_messages;
create policy "Learners can post as themselves" on public.global_messages
  for insert to authenticated with check (auth.uid() = user_id);

create index if not exists global_messages_created_at_idx on public.global_messages(created_at desc);
